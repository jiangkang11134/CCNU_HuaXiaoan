"""政策法规知识图谱本体定义。

**一族为什么不只有一种节点。** 政策类文档的实际用法不是"背文件"，而是回答
"这条要求出自哪份文件、哪一条、谁来担责"。所以真正需要被检索到的不是文件本身，
而是**文件 → 条款 → 责任主体**这条链。只用 `Document` 一个节点，图上是文件之间
连成一团，"学校党政主要负责人是第一责任人"这句话就找不到出处。

**分类口径不是编的。** 层级分类取自《教育部高校实验室安全制度体系组成》
（表2-1，见测试知识库内文档）的官方四分法：

============================  =========================================
纲领制度                       《高等学校实验室安全规范》（教科信厅函〔2023〕5号）
分项制度                       《……追责问责办法(试行)》（教科信〔2022〕4号）、
                              《……分级分类管理办法（试行）》（教科信〔2024〕4号）
指导文件                       《……加强高校实验室安全工作的意见》（教技函〔2019〕36号）、
                              《……开展加强高校实验室安全专项行动的通知》（教科信厅函〔2021〕38号）
实操标准                       《高等学校实验室安全检查项目表》等
============================  =========================================

上游还有国家法律（如《中华人民共和国安全生产法》）与校内制度（如各校《实验室安全
管理办法》），一并归入本族——它们在图上必须能和部委文件连起来，否则"校内制度依据
哪条部委文件"这个问题永远答不出来。

**这里最容易抽错的两件事，已在 schema 里写明：**

1. 印发函（如教科信〔2024〕4号）**只有文件头、没有正文**，此时只抽文件头信息，
   不许编造条款；
2. 被引用但**不在本知识库**的校内制度（100 题里引用了 5 份华中师大文件），
   只要原文点名了就必须建节点——否则条款变成孤岛。
"""

from .ontology import format_label_list, format_relation_list

#: 政策法规本体允许的实体 label。第一个是主类型。
#:
#: `PolicyRequirement` 刻意带上族前缀：实验室管理族已有 `ManagementRequirement`，
#: 若这里叫裸 `Requirement`，它就成了对方 label 的子串，跨族"是否泄漏"的守卫
#: 永远无法用简单的包含判断写出来，而且两族的要求节点在图上会难以区分。
POLICY_LABELS = (
    "PolicyDocument",
    "Provision",
    "IssuingAuthority",
    "ResponsibleParty",
    "PolicyRequirement",
    "RiskSource",
    "PolicyCategory",
    "Penalty",
)

#: 兼容旧引用：主类型单独取一个名字。
POLICY_LABEL = POLICY_LABELS[0]

POLICY_RELATIONS = (
    "ISSUED_BY",
    "HAS_PROVISION",
    "CITES",
    "BASED_ON",
    "CATEGORIZED_AS",
    "REGULATES",
    "APPLIES_TO",
    "RESPONSIBLE_FOR",
    "IMPOSES",
    "SUPERSEDES",
)

POLICY_EXTRACTION_SCHEMA = f"""
面向政策法规与管理制度文本抽取，严格依据原文，禁止常识推断与条款编造。
实体 label 只能使用：
{format_label_list(POLICY_LABELS)}
关系 label 只能使用：
{format_relation_list(POLICY_RELATIONS)}
抽取要点：
1. 文号、发文机关、施行日期、发布日期优先作为 PolicyDocument 的属性；PolicyCategory 取
   纲领制度 / 分项制度 / 指导文件 / 实操标准 / 校内制度 / 国家法律 之一。
2. Provision 必须带条款号（第X条）或条目号（一、（二）等）作为属性，并用 HAS_PROVISION
   指向所属 PolicyDocument；条内引用他文时用 BASED_ON 或 CITES 连到被引文件或条款。
3. 原文点名但不在本文件中的制度，只要被引用就要建 PolicyDocument 节点（不因缺少正文而跳过）。
4. 只有文件头、正文未随附的印发函，只抽文件头信息，不得编造条款内容。
5. ResponsibleParty 是机构或岗位角色（如学校党委、二级单位、实验室负责人、项目负责人），
   不是具体人名；出现具体姓名时只作为角色文本，不建立具体人员关系。
6. RiskSource 按原文列举建立（如剧毒、易制爆、易制毒、爆炸品、危险气体、病原微生物、
   辐射源及射线装置、同位素及核材料、危险性机械加工装置、强电强磁与激光设备、特种设备）。
7. 每条 Provision、PolicyRequirement 必须绑定原文 Chunk 证据，不得跨条款合并或改写。
""".strip()
